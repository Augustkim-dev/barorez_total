    <script>
        $(function () {
            // 전체 동의 체크박스
            let $chkAll = $('#chkAll');
            // 개별 약관 체크박스 (전체 동의는 제외)
            let $chkItems = $('input[name="chk1"]').not('#chkAll');
            // 필수 약관 체크박스 (data-required="Y" 가진 것만)
            let $requiredItems = $chkItems.filter('[data-required="Y"]');

            console.log('약관 동의 스크립트 초기화');

            // 1) 전체 동의 클릭 시: 개별 약관 전부 체크/해제
            $chkAll.on('change', function () {
                let isChecked = $(this).is(':checked');
                console.log('전체 동의 클릭:', isChecked);

                $chkItems.prop('checked', isChecked);
            });

            // 2) 개별 약관 클릭 시: 전체 동의 상태 갱신
            $chkItems.on('change', function () {
                console.log('개별 약관 클릭:', this.id, $(this).is(':checked'));

                let total = $chkItems.length;
                let checkedCount = $chkItems.filter(':checked').length;

                // 전부 체크되었으면 전체 동의도 체크, 아니면 해제
                let allChecked = (total === checkedCount);
                $chkAll.prop('checked', allChecked);

                console.log('개별 체크 상태 - 전체:', checkedCount + '/' + total, '전체동의:', allChecked);
            });

            // 3) 다음 버튼 클릭 시: 필수 약관 모두 체크되어 있는지 검사
            $('#btnNext').on('click', function () {
                let requiredTotal = $requiredItems.length;
                let requiredChecked = $requiredItems.filter(':checked').length;

                console.log('필수 약관 체크 수:', requiredChecked + '/' + requiredTotal);

                if (requiredChecked !== requiredTotal) {
                    ModalUtil.alert({
                        title: '약관',
                        message: '필수 약관(개인정보처리방침, 이용약관)에\n모두 동의해 주세요.',
                        okText: '확인',
                        onOk: function () {
                        },
                    });
                    // alert('필수 약관(개인정보처리방침, 이용약관)에 모두 동의해 주세요.');
                    return; // 이동 막기
                }

                console.log('필수 약관 모두 동의 완료, join.php로 이동');
                // 필수 약관 모두 동의한 경우에만 다음 단계로 이동
                location.href = '<?=AUTH_PAGE?>/join.php';
            });
        });
    </script>
